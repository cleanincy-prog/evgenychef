// Rebuild requested WebP derivatives with the locally installed cwebp encoder.
// Originals remain unchanged; the manifest records each original source/hash.
import { readFile, writeFile, mkdir, stat } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(await readFile(path.join(root, "scripts/site-image-manifest.json"), "utf8"));
const run = promisify(execFile);
const output = path.join(root, manifest.outputDirectory);
await mkdir(output, { recursive: true });
const records = [];
for (const item of manifest.images) {
  const source = path.join(root, "public", item.source);
  const digest = createHash("sha256").update(await readFile(source)).digest("hex");
  if (digest !== item.sourceSha256) throw new Error(`Original changed: ${item.source}`);
  const variants = [];
  for (const requestedWidth of item.widths) {
    const width = Math.min(requestedWidth, item.sourceWidth);
    const name = `${item.name}-${requestedWidth}.webp`;
    const target = path.join(output, name);
    const args = ["-quiet", "-mt", "-m", "6", "-q", String(item.quality)];
    if (item.lossless) args.push("-lossless");
    else args.push("-sharp_yuv");
    args.push("-resize", String(width), "0", source, "-o", target);
    await run(process.env.CWEBP_BINARY || "cwebp", args);
    variants.push({ url: `/media/web/${name}`, requestedWidth, width, bytes: (await stat(target)).size });
  }
  records.push({ name: item.name, role: item.role, source: item.source, sourceBytes: item.sourceBytes, variants });
}
const uniqueSources = new Map(manifest.images.map(item => [item.source, item.sourceBytes]));
const totals = {
  sourceUniqueCount: uniqueSources.size,
  sourceBytes: [...uniqueSources.values()].reduce((sum, size) => sum + size, 0),
  smallestVariantBytes: records.reduce((sum, item) => sum + item.variants[0].bytes, 0),
  largestVariantBytes: records.reduce((sum, item) => sum + item.variants.at(-1).bytes, 0),
  collageSourceBytes: manifest.images.filter(item => item.role === "collage").reduce((sum, item) => sum + item.sourceBytes, 0),
  collageSmallestBytes: records.filter(item => item.role === "collage").reduce((sum, item) => sum + item.variants[0].bytes, 0),
  collageLargestBytes: records.filter(item => item.role === "collage").reduce((sum, item) => sum + item.variants.at(-1).bytes, 0),
};
await writeFile(path.join(root, "docs/IMAGE_OPTIMIZATION_STATS.json"), JSON.stringify({ totals, images: records }, null, 2) + "\n");
const imageProps = item => {
  const original = manifest.images.find(source => source.name === item.name);
  return {
    src: item.variants.at(-1).url,
    srcSet: item.variants.map(variant => `${variant.url} ${variant.width}w`).join(", "),
    width: original.sourceWidth,
    height: original.sourceHeight,
  };
};
const heroImages = records.filter(item => item.role === "collage").map(imageProps);
const siteImages = Object.fromEntries(records.filter(item => item.role !== "collage").map(item => [item.name, imageProps(item)]));
await writeFile(path.join(root, "app/site-images.ts"),
  "// Generated by scripts/optimize-site-images.mjs; original sources are preserved in its manifest.\n" +
  `export const heroImages = ${JSON.stringify(heroImages, null, 2)} as const;\n\n` +
  `export const siteImages = ${JSON.stringify(siteImages, null, 2)} as const;\n`);
console.log(JSON.stringify(totals, null, 2));
