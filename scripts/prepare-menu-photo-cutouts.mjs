// Luminance key on an actually black photographic backdrop. Retain the
// natural gaps between panko flakes and their photographed loose fragments.
const { data, info } = await sharp(path.join(sources, "panko-paprika-2.jpg")).resize({ width: 1200 }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
const rgba = Buffer.alloc(info.width * info.height * 4);
for (let i = 0; i < info.width * info.height; i++) {
  const p = i * 3;
  const light = Math.max(data[p], data[p + 1], data[p + 2]);
  data.copy(rgba, i * 4, p, p + 3);
  rgba[i * 4 + 3] = Math.round(Math.max(0, Math.min(1, (light - 24) / 40)) * 255);
}
await sharp(rgba, { raw: { width: info.width, height: info.height, channels: 4 } }).extract({ left: 120, top: 110, width: 855, height: 656 }).resize({ width: 640 }).webp({ quality: 92, alphaQuality: 100 }).toFile(path.join(output, "panko.webp"));
