import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

// Photographic RGB only. These operations change opacity/crop/scale; no pixels
// are painted, synthesized or extended beyond the original photographed frame.
const root = process.cwd();
const sources = path.join(root, "design/sources/menu-scallops-2026-09-13");
const output = path.join(root, "public/media/menu/exploded");
await mkdir(output, { recursive: true });

async function tracedCutout(source, width, height, trace, crop, name) {
  const rgb = await sharp(path.join(sources, source)).resize({ width }).removeAlpha().raw().toBuffer();
  const alpha = await sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}"><path fill="white" d="${trace}"/></svg>`)).ensureAlpha().raw().toBuffer();
  const rgba = Buffer.alloc(width * height * 4);
  for (let i = 0; i < width * height; i++) {
    rgb.copy(rgba, i * 4, i * 3, i * 3 + 3);
    rgba[i * 4 + 3] = alpha[i * 4 + 3];
  }
  await sharp(rgba, { raw: { width, height, channels: 4 } }).extract(crop).webp({ quality: 93, alphaQuality: 100 }).toFile(path.join(output, `${name}.webp`));
}

