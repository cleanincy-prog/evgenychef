const order = heroImages.map((_, index) => index).filter(index => !heroStoryShots.some(shot => shot.index === index));
let seed = 220926;
for (let index = order.length - 1; index > 0; index--) {
  seed = (seed * 16807) % 2147483647;
  const other = seed % (index + 1);
  [order[index], order[other]] = [order[other], order[index]];
}
export const heroIntroStyles = [];
order.forEach((index, rank) => {
  const progress = rank / (order.length - 1);
  // Spread the flights across the same two seconds instead of moving 56 tiles at once.
  const delay = 330 + Math.round(500 * Math.pow(progress, .75));
  const duration = Math.round(100 - 16 * progress) + (index * 7) % 5;
  heroIntroStyles[index] = `--intro-delay:${delay}ms;--intro-duration:${duration}ms;--intro-x:60vw;--intro-y:0px;--intro-scale:${2.15 - .65 * progress};--intro-layer:${rank + 1}`;
});
heroStoryShots.forEach(shot => {
  heroIntroStyles[shot.index] = `--intro-delay:${shot.depart + shot.flight - 80}ms;--intro-duration:80ms;--intro-x:0px;--intro-y:0px;--intro-scale:1`;
});
